"""Dataset layout and metadata for generated multi-view sets.

Layouts:
- flat (turntables): images/000.png, images/001.png, ...
- rings (several elevations): views/e-20/a000.png, views/e000/a030.png, ...

Files written next to the images:
- metadata.json: everything needed to reproduce each view (reference hashes,
  seed and seed mode, prompts, steps, backend) plus the requested camera of
  every view. Camera values are *requested view metadata*, never calibration.
- transforms.json: the same requested cameras in the NeRF/Blender format that
  Pixal3D's --views-dir reads, flagged "generated_views": true, optionally with
  the normalized reference image as frame 0.
"""
from __future__ import annotations

import json
import math
import subprocess
import time
from pathlib import Path

from . import views as viewlib

CAMERA_NOTE = ("requested view metadata, not calibration: the images are generated by Qwen-Image 2.1 and "
               "nothing guarantees they match these cameras, share pixel correspondences, or form a "
               "metrically consistent set")
LAYOUTS = ("flat", "rings")


def git_commit(root: Path) -> str | None:
    try:
        out = subprocess.run(["git", "rev-parse", "HEAD"], cwd=root, capture_output=True, text=True, timeout=5)
        return out.stdout.strip() or None
    except (OSError, subprocess.TimeoutExpired):
        return None


class DatasetWriter:
    def __init__(self, root, layout: str = "flat", ext: str = "png"):
        if layout not in LAYOUTS:
            raise ValueError(f"layout must be one of {', '.join(LAYOUTS)}, got {layout!r}")
        self.root = Path(root)
        self.layout, self.ext = layout, ext
        self.root.mkdir(parents=True, exist_ok=True)

    def relpath(self, index: int, spec: viewlib.ViewSpec) -> str:
        if self.layout == "flat":
            return f"images/{index:03d}.{self.ext}"
        return f"views/{viewlib.ring_relpath(spec, self.ext)}"

    def path(self, index: int, spec: viewlib.ViewSpec) -> Path:
        path = self.root / self.relpath(index, spec)
        path.parent.mkdir(parents=True, exist_ok=True)
        return path

    def write_metadata(self, *, model: str, backend: str, seed: int, seed_mode: str, params: dict,
                       references: list[dict], preprocessing: dict | None, views: list[dict],
                       repo_root: Path | None = None) -> Path:
        document = {
            "model": "Qwen-Image-2.1",
            "model_path": model,
            "backend": backend,
            "runner_commit": git_commit(repo_root) if repo_root else None,
            "created_unix": round(time.time(), 3),
            "seed": seed,
            "seed_mode": seed_mode,
            "generation": params,
            "camera_parameters": CAMERA_NOTE,
            "references": references,
            "preprocessing": preprocessing,
            "layout": self.layout,
            "views": views,
        }
        path = self.root / "metadata.json"
        path.write_text(json.dumps(document, indent=2, default=str) + "\n")
        return path

    def write_transforms(self, frames: list[tuple[str, viewlib.ViewSpec]], *,
                         reference: tuple[str, viewlib.ViewSpec] | None = None, mesh_scale: float = 1.0) -> Path:
        """Pixal3D/NeRF-Blender transforms.json. Frame 0 defines the output
        orientation there, so the normalized reference (a real image) goes
        first when given."""
        entries = ([reference] if reference else []) + list(frames)
        if not entries:
            raise ValueError("no frames to write")
        out = []
        for relpath, spec in entries:
            out.append({
                "file_path": relpath,
                "transform_matrix": viewlib.transform_matrix(spec),
                "camera_angle_x": math.radians(spec.fov_deg),
                "name": viewlib.view_name(spec),
                "azimuth_deg": spec.azimuth_deg,
                "elevation_deg": spec.elevation_deg,
                "roll_deg": spec.roll_deg,
                "projection": spec.projection,
                "generated": not (reference and relpath == reference[0]),
            })
        document = {
            "camera_angle_x": out[0]["camera_angle_x"],
            "mesh_scale": mesh_scale,
            "generated_views": True,
            "camera_parameters": CAMERA_NOTE,
            "frames": out,
        }
        path = self.root / "transforms.json"
        path.write_text(json.dumps(document, indent=2) + "\n")
        return path
